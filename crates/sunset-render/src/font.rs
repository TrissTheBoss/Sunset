#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_glyphs_match_expected_bitmaps() {
        assert_eq!(
            glyph_rows('0'),
            Some([0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E])
        );
        assert_eq!(
            glyph_rows('A'),
            Some([0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11])
        );
        assert_eq!(glyph_rows(' '), Some([0x00; 7]));
    }

    #[test]
    fn unsupported_character_is_none() {
        assert_eq!(glyph_rows('!'), None);
        assert_eq!(glyph_rows('a'), None);
    }

    #[test]
    fn every_supported_glyph_has_seven_rows() {
        for ch in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ .:-".chars() {
            assert!(glyph_rows(ch).is_some(), "{ch}");
        }
    }
}
